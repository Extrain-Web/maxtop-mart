/**
 * Build the web-sized logo files from the original artwork.
 *
 *   public/images/logo.png                 source artwork (currently 5225 px, ~21 MB)
 *     -> public/images/brand/logo.webp      full lockup, 320 px tall
 *     -> public/images/brand/logo-mark.webp winged shield without the wordmark, 256 px tall
 *     -> src/app/icon.png                   browser-tab icon (shield only), 192 x 192
 *     -> src/components/shared/logoAsset.ts paths (with a content hash) + sizes for <Logo>
 *
 * Run after replacing public/images/logo.png:  npm run logo
 * The mark and icon crops assume the stacked layout of the current logo
 * (emblem on top, wordmark underneath).
 */
import sharp from 'sharp';
import { createHash } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'public/images/logo.png');
const BRAND_DIR = path.join(ROOT, 'public/images/brand');
const ICON = path.join(ROOT, 'src/app/icon.png');
const ASSET_MODULE = path.join(ROOT, 'src/components/shared/logoAsset.ts');

const LOGO_HEIGHT = 320;
const MARK_HEIGHT = 256;
const ICON_SIZE = 192;
const ALPHA_MIN = 8;   // pixels at or below this alpha count as empty
const PAD = 0.006;     // breathing room around crops, as a share of the artwork height
// The shield is the middle of the winged emblem. The tab icon uses only the shield
// because the wings make the "F" unreadable at 16-32 px.
const SHIELD_LEFT = 0.185;
const SHIELD_WIDTH = 0.63;

const { data, info } = await sharp(SRC).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
const W = info.width;
const H = info.height;
const alpha = (x, y) => data[(y * W + x) * 4 + 3];

function bounds(x0, y0, x1, y1) {
    let minX = x1, minY = y1, maxX = -1, maxY = -1;
    for (let y = y0; y < y1; y++) {
        for (let x = x0; x < x1; x++) {
            if (alpha(x, y) > ALPHA_MIN) {
                if (x < minX) minX = x;
                if (x > maxX) maxX = x;
                if (y < minY) minY = y;
                if (y > maxY) maxY = y;
            }
        }
    }
    if (maxX < 0) throw new Error('logo.png is fully transparent');
    return { left: minX, top: minY, width: maxX - minX + 1, height: maxY - minY + 1 };
}

function pad(box, amount) {
    const left = Math.max(0, box.left - amount);
    const top = Math.max(0, box.top - amount);
    const right = Math.min(W, box.left + box.width + amount);
    const bottom = Math.min(H, box.top + box.height + amount);
    return { left, top, width: right - left, height: bottom - top };
}

// Whole artwork, then the emblem above the emptiest row between emblem and wordmark.
const all = bounds(0, 0, W, H);
let split = all.top + all.height;
let fewest = Infinity;
for (let y = all.top + Math.floor(all.height * 0.65); y < all.top + Math.floor(all.height * 0.92); y++) {
    let n = 0;
    for (let x = all.left; x < all.left + all.width; x++) if (alpha(x, y) > ALPHA_MIN) n++;
    if (n < fewest) { fewest = n; split = y; }
}
const emblem = bounds(all.left, all.top, all.left + all.width, split);
const shield = {
    left: emblem.left + Math.round(emblem.width * SHIELD_LEFT),
    top: emblem.top,
    width: Math.round(emblem.width * SHIELD_WIDTH),
    height: emblem.height,
};

const padPx = Math.round(all.height * PAD);
const source = () => sharp(data, { raw: { width: W, height: H, channels: 4 } });
const webp = { quality: 90, alphaQuality: 100, effort: 6 };

const logo = await source().extract(pad(all, padPx)).resize({ height: LOGO_HEIGHT }).webp(webp).toBuffer({ resolveWithObject: true });
const mark = await source().extract(pad(emblem, padPx)).resize({ height: MARK_HEIGHT }).webp(webp).toBuffer({ resolveWithObject: true });
const icon = await source().extract(shield)
    .resize(ICON_SIZE, ICON_SIZE, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .png({ compressionLevel: 9 }).toBuffer();

await mkdir(BRAND_DIR, { recursive: true });
await writeFile(path.join(BRAND_DIR, 'logo.webp'), logo.data);
await writeFile(path.join(BRAND_DIR, 'logo-mark.webp'), mark.data);
await writeFile(ICON, icon);

const hash = (buf) => createHash('sha1').update(buf).digest('hex').slice(0, 8);
await writeFile(ASSET_MODULE,
    `// Generated by scripts/build-logo.mjs from public/images/logo.png. Do not edit by hand; run \`npm run logo\`.\n` +
    `export const LOGO = { src: '/images/brand/logo.webp?v=${hash(logo.data)}', width: ${logo.info.width}, height: ${logo.info.height} } as const;\n` +
    `export const LOGO_MARK = { src: '/images/brand/logo-mark.webp?v=${hash(mark.data)}', width: ${mark.info.width}, height: ${mark.info.height} } as const;\n`);

const kb = (n) => `${(n / 1024).toFixed(1)} KB`;
console.log(`source          ${W}x${H}`);
console.log(`logo.webp       ${logo.info.width}x${logo.info.height}  ${kb(logo.data.length)}`);
console.log(`logo-mark.webp  ${mark.info.width}x${mark.info.height}  ${kb(mark.data.length)}`);
console.log(`icon.png        ${ICON_SIZE}x${ICON_SIZE}  ${kb(icon.length)}`);
